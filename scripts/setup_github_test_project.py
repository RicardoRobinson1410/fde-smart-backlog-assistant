"""End-to-end GitHub PAT test case: creates repo, seeds baseline backlog issues, analyzes notes against live GitHub backlog, and exports new stories."""

from __future__ import annotations

import argparse
import json
import sys
import urllib.error
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))

from backlog_assistant.config import load_scenario_config
from backlog_assistant.engine import BacklogEngine
from backlog_assistant.parser import (
    _github_api_request,
    _resolve_github_pat,
    export_stories_to_github,
    load_existing_backlog,
)


def ensure_github_repo(repo_full_name: str, token: str, private: bool = False) -> str:
    """Ensure the target GitHub repository exists via GitHub PAT REST API."""
    owner, repo_name = repo_full_name.split("/", 1)
    check_url = f"https://api.github.com/repos/{repo_full_name}"
    try:
        info = _github_api_request(check_url, token=token, method="GET")
        if isinstance(info, dict) and info.get("html_url"):
            print(f"[OK] Repository already exists: {info['html_url']}")
            return str(info["html_url"])
    except urllib.error.HTTPError as err:
        if err.code != 404:
            raise

    print(f"[CREATE] Creating repository '{repo_full_name}' via GitHub PAT REST API...")
    created = _github_api_request(
        "https://api.github.com/user/repos",
        token=token,
        method="POST",
        payload={
            "name": repo_name,
            "description": "Configurable FDE Smart Backlog Assistant — Certified-Level RDE Project & Live Backlog Testbed",
            "private": private,
            "has_issues": True,
            "auto_init": False,
        },
    )
    html_url = str(created.get("html_url", f"https://github.com/{repo_full_name}"))
    print(f"[CREATED] {html_url}")
    return html_url


def ensure_labels(repo_full_name: str, token: str) -> None:
    """Create standard FDE labels in the GitHub repository if missing."""
    labels = [
        ("baseline-backlog", "0e8a16", "Existing baseline backlog item seeded from existing_backlog.json"),
        ("fde-generated", "1d76db", "Net-new user story generated by FDE Smart Backlog Assistant"),
        ("backlog-assistant", "5319e7", "Managed by FDE Smart Backlog Assistant"),
    ]
    for name, color, desc in labels:
        try:
            _github_api_request(
                f"https://api.github.com/repos/{repo_full_name}/labels",
                token=token,
                method="POST",
                payload={"name": name, "color": color, "description": desc},
            )
        except urllib.error.HTTPError:
            pass  # Label already exists


def seed_baseline_backlog_issues(repo_full_name: str, token: str, backlog_json_path: Path) -> list[str]:
    """Seed the repository's GitHub Issues with FIN-101..FIN-106 if not already present."""
    existing_live = load_existing_backlog(backlog_path=None, github_repo=repo_full_name)
    existing_ids = {item.id for item in existing_live}

    baseline_items = json.loads(backlog_json_path.read_text(encoding="utf-8"))
    created_urls: list[str] = []

    for item in baseline_items:
        item_id = item["id"]
        if item_id in existing_ids:
            print(f"[SKIP] Baseline issue [{item_id}] already exists in {repo_full_name}")
            continue
        title = f"[{item_id}] {item['title']}"
        body = (
            f"**Baseline Backlog Item ID:** `{item_id}`\n"
            f"**Priority:** `{item['priority']}` | **Category:** `{item['category']}` | **Status:** `{item['status']}`\n\n"
            f"### Summary\n{item['summary']}"
        )
        res = _github_api_request(
            f"https://api.github.com/repos/{repo_full_name}/issues",
            token=token,
            method="POST",
            payload={"title": title, "body": body, "labels": ["baseline-backlog", "backlog-assistant"]},
        )
        url = str(res.get("html_url", "")) if isinstance(res, dict) else ""
        print(f"[SEEDED] {title} -> {url}")
        created_urls.append(url)
    return created_urls


def main() -> None:
    parser = argparse.ArgumentParser(description="Create GitHub project + seed backlog + run live PAT test case.")
    parser.add_argument("--repo", default="RicardoRobinson1410/fde-smart-backlog-assistant")
    parser.add_argument("--private", action="store_true", default=False)
    args = parser.parse_args()

    token = _resolve_github_pat()
    if not token:
        raise RuntimeError("No GitHub PAT found in GITHUB_PAT, GITHUB_TOKEN, or `gh auth token`.")

    # 1. Create or verify the GitHub repository using PAT
    repo_url = ensure_github_repo(args.repo, token=token, private=args.private)
    ensure_labels(args.repo, token=token)

    # 2. Seed the baseline backlog (FIN-101..FIN-106) as GitHub Issues
    seed_baseline_backlog_issues(args.repo, token=token, backlog_json_path=Path("data/existing_backlog.json"))

    # 3. Pull the live backlog from GitHub via PAT and run the BacklogEngine analysis
    cfg = load_scenario_config().with_overrides({"github.enabled": True, "github.repo": args.repo})
    engine = BacklogEngine(config=cfg, force_offline=True)
    result = engine.analyze("data/samples/01_sprint_planning_notes.txt", backlog_path="", github_repo=args.repo)
    print(
        f"\n[ANALYZED LIVE BACKLOG] Pulled {result.metadata.existing_backlog_count} open GitHub issues from {args.repo} "
        f"and extracted {len(result.stories)} stories:"
    )
    for s in result.stories:
        print(f"  - {s.id} [{s.backlog_alignment.value}] {s.title} (Refs: {s.related_backlog_ids})")

    # 4. Export NEW stories back to GitHub Issues (only if not already exported)
    live_after = load_existing_backlog(backlog_path=None, github_repo=args.repo)
    live_ids = {i.id for i in live_after}
    new_to_export = [s for s in result.stories if s.id not in live_ids]
    if new_to_export:
        exported = export_stories_to_github(
            new_to_export,
            repo=args.repo,
            labels=cfg.github.issue_labels,
            dry_run=False,
        )
        for url in exported:
            print(f"[EXPORTED NEW STORY TO GITHUB] {url}")
    else:
        print("[OK] Generated NEW stories are already present in GitHub Issues.")

    print(f"\n[COMPLETE] Live GitHub Project & Backlog Test Case URL: {repo_url}/issues")


if __name__ == "__main__":
    main()
